#!/usr/bin/env python3
"""Bundle the canonical JSON datasets into a single browser-ready file.

Outputs `docs/data.js` (assigns `window.DENTRX`) so the web app is fully static and
works offline / from file:// with no fetch and no server. Also syncs the datasets into
`dentrx/data/` so the Python wheel is self-contained.

Run from the repo root:  python scripts/build_web_data.py
"""

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOCS = ROOT / "docs"
PKG_DATA = ROOT / "dentrx" / "data"


def main() -> None:
    sources = json.loads((DATA / "sources.json").read_text(encoding="utf-8"))
    pillars = {}
    for f in sorted(DATA.glob("*.json")):
        if f.name == "sources.json":
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        pillars[d["pillar"]] = d

    bundle = {
        "version": "0.1.0",
        "sources": sources["sources"],
        "pillars": pillars,
    }

    DOCS.mkdir(exist_ok=True)
    out = DOCS / "data.js"
    out.write_text(
        "/* AUTO-GENERATED by scripts/build_web_data.py — do not edit by hand. */\n"
        "window.DENTRX = " + json.dumps(bundle, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )

    # keep a copy inside the package so the installed wheel is self-contained
    PKG_DATA.mkdir(parents=True, exist_ok=True)
    for f in DATA.glob("*.json"):
        shutil.copy2(f, PKG_DATA / f.name)

    n_rules = sum(len(p.get("rules", [])) for p in pillars.values())
    print(f"Wrote {out.relative_to(ROOT)}  ({len(pillars)} pillars, {n_rules} rules)")
    print(f"Synced {len(list(DATA.glob('*.json')))} data files -> {PKG_DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
